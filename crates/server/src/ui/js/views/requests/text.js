  // Label of a backend code, or "" when there is none (the code itself is then the text).
  const maybe = key => (I18n.has(key) ? t(key) : "");
  const errLabel = code => (code ? maybe("requests.err." + code) : "");
  const errTip = code => (code ? maybe("requests.errTip." + code) : "");
  const causeLabel = (problem, cause) => (problem && cause ? maybe("requests.c." + problem + "." + cause) : "");
  const outcomeLabel = o => maybe("requests.o." + o) || o || "";
  const sourceLabel = s => maybe("requests.src." + s) || s || "";
  const sourceTip = s => maybe("requests.srcTip." + s);
  const tierLabel = tier => (tier ? maybe("requests.tier." + tier) || tier : I18n.t("ui.none"));
  const nextLabel = k => maybe("requests.next." + k);
  const nextTip = k => maybe("requests.nextTip." + k);
  const refusalLabel = r => maybe("requests.r." + r) || r || "";
  const refusalTip = r => maybe("requests.rTip." + r);

  // Attempt action text: ok / switch / stop / refresh+retry / retry(1500ms) / cooldown(30s)+switch.
  function actionText(a) {
    if (!a) return "";
    if (I18n.has("requests.d.act." + a)) return t("requests.d.act." + a);
    let m = /^retry\((\d+)ms\)$/.exec(a);
    if (m) return t("requests.d.act.retry", {s: (Number(m[1]) / 1000).toFixed(1)});
    m = /^cooldown\((\d+)s\)\+([\w+]+)$/.exec(a);
    if (m) return t("requests.d.act.cooldown", {s: m[1], then: actionText(m[2])});
    return a;
  }

  return {errLabel, errTip, causeLabel, outcomeLabel, sourceLabel, sourceTip, tierLabel, nextLabel, nextTip, refusalLabel,
    refusalTip, actionText};
